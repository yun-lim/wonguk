function seoulYear(now = new Date()) {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    year: "numeric",
  }).formatToParts(now);
  return Number(parts.find((p) => p.type === "year")?.value);
}

function elementMix(elements, luckEl) {
  if (!luckEl) {
    return "지금은 대운의 오행이 뚜렷하지 않아, 원국의 과불급이 더 크게 읽힌다.";
  }
  const count = elements[luckEl] ?? 0;
  if (count === 0) {
    return `원국 겉글자에 없던 ${iGa(luckEl)} 대운으로 들어온다. 생소한 결이 열리거나, 안 쓰던 근육을 쓰게 되는 시기다. 갑자기 커진 기운을 전부 성격으로 받아들이지 말고, 십 년 바탕의 연습으로 보라.`;
  }
  if (count >= 3) {
    return `이미 많은 ${luckEl} 위에 같은 기운이 겹친다. 익숙한 힘이 커지되, 과하면 막힌다. 같은 버릇을 한 가지 줄이는 것이 올해의 보정이다.`;
  }
  return `원국의 ${eulReul(luckEl)} 대운이 한 겹 보탠다. 이미 아는 결이 조금 더 잘 쓰이는 시기다. 새 인격이 오는 것이 아니라, 있던 도구가 손에 맞는 쪽에 가깝다.`;
}

function elementAdvice(elements, hourUnknown) {
  const missing = ELEMENTS.filter((e) => elements[e] === 0);
  const excess = ELEMENTS.filter((e) => elements[e] >= 3);
  const basis = hourUnknown ? "연·월·일 여섯 글자" : "연·월·일·시 여덟 글자";
  const bits = [];
  bits.push(`${basis}만 센 결과다. 지장간은 넣지 않았다.`);
  if (excess.length) {
    bits.push(`${iGa(joinKo(excess))} 많아 자리가 넓다. 이 기운이 하는 일만 되풀이하면 과부하가 먼저 온다.`);
  }
  if (missing.length) {
    bits.push(
      `${eunNeun(joinKo(missing))} 겉글자에 없다. 인생에 없는 것이 아니나, 원국만 보면 이 결을 일부러 연습해야 드러난다.`,
    );
  }
  if (!excess.length && !missing.length) {
    bits.push("크게 치우친 글자는 없다. 과불급보다 흘려 쓰는 자리, 곧 대운과 일상의 리듬이 더 중요하다.");
  }
  return bits.join(" ");
}

function luckLine(luck, age) {
  if (!luck) return "대운을 계산하지 못했습니다. 원국의 일간과 오행만으로 읽습니다.";
  const dir = luck.forward ? "순행" : "역행";
  if (luck.beforeFirst || !luck.current) {
    return `아직 첫 대운 전이다. 대운수는 약 ${luck.startAge}세(만나이). ${dir}. 지금은 원국, 특히 월주의 바탕이 더 크게 읽힌다.`;
  }
  const cur = luck.current;
  const hint = GOD_HINT[cur.stem.god || ""] || cur.stem.god || "";
  return `만나이 ${age}세, ${cur.start}–${cur.end}세 ${cur.hanja}(${cur.korean}) 대운. ${dir}. 대운 천간은 일간 대비 ${cur.stem.god}${hint ? ` — ${hint}` : ""}. 대운은 10년 바탕이지 올해의 세부가 아니다.`;
}

function dayMasterLine(dm) {
  return `${dm.yinyang}${dm.element} 일간 ${dm.hanja}${dm.stem}.`;
}

